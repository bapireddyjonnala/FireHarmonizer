export function searchRegions(query: string): RegionInfo[] {
  const clean = query.trim().toLowerCase();
  if (!clean) return [];

  return REGIONS_DATA.filter((region) => {
    const nameMatch = region.name.toLowerCase().includes(clean);
    const countryMatch = region.country?.toLowerCase().includes(clean);
    const categoryMatch = region.category.toLowerCase().includes(clean);
    return nameMatch || countryMatch || categoryMatch;
  });
}

