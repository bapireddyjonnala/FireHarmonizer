all_entries = []
seen_ids = set()

def add_entry(entry):
    base_id = slugify(entry["id"])
    eid = base_id
    counter = 1
    while eid in seen_ids:
        counter += 1
        eid = f"{base_id}-{counter}"
    entry["id"] = eid
    seen_ids.add(eid)
    
    # Validate bounding box: west < east, south < north, within limits
    west, south, east, north = (
        entry["bounds"]["west"],
        entry["bounds"]["south"],
        entry["bounds"]["east"],
        entry["bounds"]["north"],
    )
    assert -180.0 <= west <= 180.0, f"Invalid west {west} in {entry['name']}"
    assert -180.0 <= east <= 180.0, f"Invalid east {east} in {entry['name']}"
    assert -90.0 <= south <= 90.0, f"Invalid south {south} in {entry['name']}"
    assert -90.0 <= north <= 90.0, f"Invalid north {north} in {entry['name']}"
    assert west < east, f"west >= east in {entry['name']}: {west} >= {east}"
    assert south < north, f"south >= north in {entry['name']}: {south} >= {north}"
    lat, lon = entry["center"][0], entry["center"][1]
    assert south <= lat <= north, f"Center lat {lat} outside bounds in {entry['name']}: [{south}, {north}]"
    assert west <= lon <= east, f"Center lon {lon} outside bounds in {entry['name']}: [{west}, {east}]"
    
    all_entries.append(entry)

